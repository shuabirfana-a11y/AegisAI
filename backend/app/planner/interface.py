from typing import Protocol
from app.planner.schemas import (ModelIdentity, PlannerInput, PlannerContext,
                                 PlanningOutcome, PlannerAttempt)

class PlannerTraceSink(Protocol):
    def record_attempt(self, context: PlannerContext, attempt: PlannerAttempt) -> None:...

class TaskPlanner(Protocol):
    @property
    def model_identity(self) -> ModelIdentity:...
    @property
    def prompt_version(self) -> str:...
    @property
    def registry_version(self) -> str:...
    def plan(self, input: PlannerInput, context: PlannerContext) -> PlanningOutcome:...
